export const APP_STATES = Object.freeze({
  IDLE: 'idle',
  ANALYZING: 'analyzing',
  SUCCESS: 'success',
  ERROR: 'error',
})

export const APP_ACTIONS = Object.freeze({
  START_ANALYSIS: 'START_ANALYSIS',
  FINISH_ANALYSIS: 'FINISH_ANALYSIS',
  STOP_ANALYSIS: 'STOP_ANALYSIS',
  ANALYSIS_FAILED: 'ANALYSIS_FAILED',
  FILES_CHANGED: 'FILES_CHANGED',
  RESET_SCAN: 'RESET_SCAN',
})

const transitions = {
  [APP_ACTIONS.START_ANALYSIS]: {
    [APP_STATES.IDLE]: APP_STATES.ANALYZING,
    [APP_STATES.ERROR]: APP_STATES.ANALYZING,
  },
  [APP_ACTIONS.FINISH_ANALYSIS]: {
    [APP_STATES.ANALYZING]: APP_STATES.SUCCESS,
  },
  [APP_ACTIONS.STOP_ANALYSIS]: {
    [APP_STATES.ANALYZING]: APP_STATES.IDLE,
  },
  [APP_ACTIONS.ANALYSIS_FAILED]: {
    [APP_STATES.IDLE]: APP_STATES.ERROR,
    [APP_STATES.ANALYZING]: APP_STATES.ERROR,
  },
  [APP_ACTIONS.FILES_CHANGED]: {
    [APP_STATES.IDLE]: APP_STATES.IDLE,
    [APP_STATES.SUCCESS]: APP_STATES.IDLE,
    [APP_STATES.ERROR]: APP_STATES.IDLE,
  },
  [APP_ACTIONS.RESET_SCAN]: {
    [APP_STATES.IDLE]: APP_STATES.IDLE,
    [APP_STATES.ANALYZING]: APP_STATES.IDLE,
    [APP_STATES.SUCCESS]: APP_STATES.IDLE,
    [APP_STATES.ERROR]: APP_STATES.IDLE,
  },
}

export function appStateReducer(state, action) {
  return transitions[action.type]?.[state] ?? state
}
